"""Regenerate the numeric tables used in reports/report.md -> reports/tables.md.

Run after any re-run of the pipeline so the report's tables stay in sync:
    python src/report_tables.py
"""
import json

import pandas as pd

from config import REPORTS


def md(df, floatfmt=".3g"):
    return df.to_markdown(index=False, floatfmt=floatfmt)


def section(title, body):
    return f"\n### {title}\n\n{body}\n"


def benchmark(path, label):
    if not path.exists():
        return section(label, "_not run yet_")
    b = pd.read_csv(path)
    out = []
    reg = b[b.task == "regression"][["model", "features", "MAE", "RMSE", "R2", "bias", "MAE_top5pct",
                                     "cat_acc", "skill_vs_persistence_pct", "fit_s", "size_mb"]]
    out.append(section(f"{label}: regression (AQI of D+1), test 2022-01..2023-03", md(reg, ".2f")))
    cls = b[b.task.isin(["derived_cls", "direct_cls"])][["model", "features", "task", "precision", "recall",
                                                        "F1", "PR_AUC", "ROC_AUC", "balanced_acc", "threshold"]]
    out.append(section(f"{label}: Poor-or-worse (AQI > 200) classification", md(cls, ".3f")))
    raw = b[(b.features == "raw")].set_index(["model", "task"])
    pca = b[(b.features == "pca")].set_index(["model", "task"])
    j = raw.join(pca, lsuffix="_raw", rsuffix="_pca", how="inner").reset_index()
    j["dMAE"] = j.MAE_pca - j.MAE_raw
    j["dF1"] = j.F1_pca - j.F1_raw
    pc = j[["model", "task", "MAE_raw", "MAE_pca", "dMAE", "F1_raw", "F1_pca", "dF1", "fit_s_raw", "fit_s_pca"]]
    out.append(section(f"{label}: PCA (95 % variance) vs raw features", md(pc, ".3f")))
    return "".join(out)


def csv_table(name, title, cols=None, n=None, fmt=".3g"):
    p = REPORTS / name
    if not p.exists():
        return section(title, "_not run yet_")
    d = pd.read_csv(p).rename(columns={"Unnamed: 0": ""})
    if cols:
        d = d[[c for c in cols if c in d.columns]]
    if n:
        d = d.head(n)
    return section(title, md(d, fmt))


def main():
    parts = ["# Result tables (auto-generated by src/report_tables.py, do not edit)\n"]
    parts.append(benchmark(REPORTS / "benchmark.csv", "Benchmark"))
    imp = json.loads((REPORTS / "imputation_results.json").read_text())
    parts.append(section("Imputation: reconstruction of masked daily PM2.5 (µg/m³)",
                         md(pd.DataFrame(imp["reconstruction"]), ".3f")))
    parts.append(section("Imputation: downstream XGBoost on validation 2021",
                         md(pd.DataFrame(imp["downstream"]), ".3f")))
    if "downstream_after_daily_hybrid" in imp:
        parts.append(section("Imputation: downstream after daily hybrid fill of the lag history",
                             md(pd.DataFrame(imp["downstream_after_daily_hybrid"]), ".3f")))
    parts.append(csv_table("leakage_audit.csv", "Leakage audit"))
    parts.append(csv_table("ablation.csv", "Analysis A: ablation", fmt=".3f"))
    parts.append(csv_table("efficiency.csv", "Analysis C: efficiency", fmt=".4g"))
    parts.append(csv_table("efficiency_scaling.csv", "Analysis C: training-size scaling", fmt=".4g"))
    for f, t in [("errors_region.csv", "Analysis E: MAE by region"),
                 ("errors_month.csv", "Analysis E: MAE by target month"),
                 ("errors_true_cat_mae.csv", "Analysis E: MAE by true AQI category"),
                 ("errors_true_cat_bias.csv", "Analysis E: bias by true AQI category"),
                 ("errors_change.csv", "Analysis E: MAE by size of day-to-day change"),
                 ("errors_diwali.csv", "Analysis E: Diwali window"),
                 ("errors_gap.csv", "Analysis E: MAE vs data gaps")]:
        parts.append(csv_table(f, t, fmt=".2f"))
    parts.append(csv_table("loco.csv", "Leave-one-city-out", fmt=".2f"))
    (REPORTS / "tables.md").write_text("".join(parts), encoding="utf-8")
    print("wrote", REPORTS / "tables.md")


if __name__ == "__main__":
    main()
